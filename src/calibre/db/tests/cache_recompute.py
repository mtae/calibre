    def close(self):
        if self.cache.is_closed:
            return
        self.cache.close()
        if self.cache in self.test.objects_to_close:
            self.test.objects_to_close.remove(self.cache)

    def run(self, ops, check=True):
        """
        Apply the operations, checking the live cache against a fresh cache
        after every one. Return None if the checks all pass, otherwise a tuple
        (index of the operation, key of the observation, description)
        """
        for i, op in enumerate(ops):
            self.apply(op)
            if check:
                diff = self.compare()
                if diff is not None:
                    return (i, *diff)


