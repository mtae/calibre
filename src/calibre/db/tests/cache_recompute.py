    # Operations {{{
    def apply(self, op):
        "Apply the operation to the live cache. Return False if it was not applicable to the current state"
        return getattr(self, 'op_' + op[0])(*op[1:]) is not False

    def have(self, *book_ids):
        return all(self.cache.has_id(b) for b in book_ids)

    def op_set_field(self, field, val_map):
        if not self.have(*val_map):
            return False
        self.cache.set_field(field, val_map)

    def op_set_metadata(self, book_id, changes, force_changes):
        if not self.have(book_id):
            return False
        mi = self.cache.get_metadata(book_id)
        for k, v in changes.items():
            mi.set(k, v)
        self.cache.set_metadata(book_id, mi, force_changes=force_changes)

    def op_add_format(self, book_id, fmt, size):
        if not self.have(book_id):
            return False
        self.cache.add_format(book_id, fmt, BytesIO(b'x' * size))

    def op_remove_formats(self, book_id, fmts):
        if not self.have(book_id):
            return False
        self.cache.remove_formats({book_id: fmts})

    def op_set_cover(self, book_id, has_cover):
        if not self.have(book_id):
            return False
        self.cache.set_cover({book_id: IMG if has_cover else None})

    def op_rename_items(self, field, old, new):
        ids = self.cache.get_item_ids(field, [old], case_sensitive=True)
        if ids.get(old) is None:
            return False
        self.cache.rename_items(field, {ids[old]: new})

    def op_remove_items(self, field, names):
        ids = [i for i in self.cache.get_item_ids(field, names, case_sensitive=True).values() if i is not None]
        if not ids:
            return False
        self.cache.remove_items(field, ids)

    def op_add_book(self, title, authors, tags, series, series_index, fmts):
        from calibre.ebooks.metadata.book.base import Metadata

        mi = Metadata(title, authors)
        mi.tags, mi.series, mi.series_index = tags, series, series_index
        self.cache.add_books([(mi, {f: BytesIO(b'new ' + f.encode()) for f in fmts})])

    def op_remove_book(self, book_id):
        if not self.have(book_id):
            return False
        self.cache.remove_books((book_id,), permanent=True)

    def op_set_link_map(self, field, name, link):
        self.cache.set_link_map(field, {name: link})

    def op_set_notes(self, field, name, text):
        ids = self.cache.get_item_ids(field, [name], case_sensitive=True)
        if ids.get(name) is None:
            return False
        self.cache.set_notes_for(field, ids[name], text, text)

    def op_set_sort_for_authors(self, name, sort):
        ids = self.cache.get_item_ids('authors', [name], case_sensitive=True)
        if ids.get(name) is None:
            return False
        self.cache.set_sort_for_authors({ids[name]: sort})

    def op_merge_book_metadata(self, dest, srcs):
        if not self.have(dest, *srcs):
            return False
        self.cache.merge_book_metadata(dest, srcs)

    def op_add_extra_files(self, book_id, relpath, size):
        if not self.have(book_id):
            return False
        self.cache.add_extra_files(book_id, {relpath: BytesIO(b'e' * size)})

    def op_remove_extra_files(self, book_id, relpath):
        if not self.have(book_id):
            return False
        self.cache.remove_extra_files(book_id, [relpath], permanent=True)

    def op_dump_metadata(self, book_ids):
        if not self.have(*book_ids):
            return False
        self.cache.dump_metadata(book_ids)

    def op_mark(self, book_ids):
        # Marked books are a property of the View, which clears the search cache of the Cache for them
        self.view.set_marked_ids({b for b in book_ids if self.cache.has_id(b)})

    def op_saved_search(self, action, name, val):
        c = self.cache
        if action == 'add':
            c.saved_search_add(name, val)
        elif action == 'delete':
            if name not in c.saved_search_names():
                return False
            c.saved_search_delete(name)
        else:
            if name not in c.saved_search_names() or val in c.saved_search_names():
                return False
            c.saved_search_rename(name, val)

    def op_set_pref(self, name, val):
        self.cache.set_pref(name, val)

    def generate(self, rng):
        "Generate a random operation that is applicable to the current state"
        cache = self.cache
        ids = sorted(cache.all_book_ids())
        while True:
            kind = rng.choices(OP_KINDS, OP_WEIGHTS)[0]
            op = getattr(self, 'gen_' + kind)(rng, cache, ids)
            if op is not None:
                return op

    def pick_books(self, rng, ids, n=None):
        n = n or rng.choice((1, 1, 1, 2, 3))
        return sorted(rng.sample(ids, min(n, len(ids))))

    def gen_set_field(self, rng, cache, ids):
        field = rng.choice(SET_FIELDS)
        books = self.pick_books(rng, ids)
        val_map = {b: value_for(rng, field) for b in books}
        return 'set_field', field, val_map

    def gen_set_metadata(self, rng, cache, ids):
        changes = {}
        for field in rng.sample(META_FIELDS, rng.randint(1, 4)):
            changes[field] = value_for(rng, field)
        return 'set_metadata', rng.choice(ids), changes, rng.random() < 0.5

