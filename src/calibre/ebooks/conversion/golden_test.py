        def test_deterministic_across_processes(self):
            # Different hash seeds (and addresses) must not change the output
            # at all when the random values are fixed with SOURCE_DATE_EPOCH.
            from calibre.utils.ipc.simple_worker import fork_job

            with TemporaryDirectory('_golden_det') as tdir:
                results = []
                for seed in ('1', '2'):
                    sdir = os.path.join(tdir, seed)
                    os.makedirs(os.path.join(sdir, 'out'))
                    env = {'PYTHONHASHSEED': seed, 'SOURCE_DATE_EPOCH': SOURCE_DATE_EPOCH}
                    r = fork_job(
                        'calibre.ebooks.conversion.golden_test',
                        'convert_in_worker',
                        args=(sdir, os.path.join(sdir, 'out')),
                        env=env,
                        no_output=True,
                        timeout=240,
                    )
                    results.append(r['result'])
                self.assertEqual(results[0].keys(), results[1].keys())
                for k in results[0]:
                    self.assertEqual(results[0][k], results[1][k], f'{k} differs between runs with different hash seeds')

