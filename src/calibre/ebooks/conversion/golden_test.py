def sha(data):
    if isinstance(data, str):
        data = data.encode('utf-8')
    return hashlib.sha256(data).hexdigest()[:16]


def summarize_mobi(path):
    from calibre.ebooks.mobi.debug.headers import MOBIFile, TextRecord
    from calibre.utils.imghdr import identify

    with open(path, 'rb') as f:
        mf = MOBIFile(f)
    mh = mf.mobi_header
    decompress = mf.decompress8 if mf.kf8_type == 'standalone' else mf.decompress6
    ntr = mh.number_of_text_records
    texts = [TextRecord(i, mf.records[i], mh.extra_data_flags, decompress) for i in range(1, ntr + 1)]
    text = b''.join(t.raw for t in texts)
    ans = {
        'header': {
            'compression': mh.compression_raw.hex(),
            'text_length': mh.text_length,
            'text_records': ntr,
            'header_length': mh.length,
            'type': mh.type_raw,
            'encoding': mh.encoding_raw,
            'version': mh.file_version,
            'extra_data_flags': mh.extra_data_flags,
            'records': len(mf.records),
        },
        'text': {'length': len(text), 'sha': sha(text), 'records': [sha(t.raw) for t in texts]},
        'trailing': sha(b''.join(t.trailing_data['raw_bytes'] for t in texts)),
        'records': [],
    }
    for i in range(ntr + 1, len(mf.records)):
        raw = mf.records[i].raw
        fmt = None
        if raw[:4] in (b'\x89PNG', b'GIF8') or raw[:2] == b'\xff\xd8':
            fmt, w, h = identify(raw)
        if fmt:
            ans['records'].append(['image', fmt, w, h])
        elif len(raw) <= 3 and not raw.strip(b'\0'):
            ans['records'].append(['pad', len(raw)])
        else:
            kind = raw[:4].decode('ascii') if raw[:4].isalpha() and raw[:4].isupper() else 'data'
            ans['records'].append([kind, len(raw), sha(raw)])
    return ans


def normalize_xml(raw, name):
    """Canonical form of an XML file with the values that legitimately change from run to run masked"""
    from lxml import etree

    root = etree.fromstring(raw)
    ns = {'dc': 'http://purl.org/dc/elements/1.1/', 'opf': 'http://www.idpf.org/2007/opf', 'ncx': 'http://www.daisy.org/z3986/2005/ncx/'}
    scheme = '{http://www.idpf.org/2007/opf}scheme'
    if name.endswith('.opf'):
        for x in root.xpath('//dc:contributor[@opf:role="bkp"]', namespaces=ns):
            x.getparent().remove(x)  # calibre (version)
        for x in root.xpath('//dc:identifier', namespaces=ns):
            if (x.get(scheme) or '').lower() in ('uuid', 'calibre'):
                x.text = 'MASKED'
        for x in root.xpath('//opf:meta[@name="calibre:timestamp"]', namespaces=ns):
            x.set('content', 'MASKED')
    elif name.endswith('.ncx'):
        for x in root.xpath('//ncx:meta[@name="dtb:uid"]', namespaces=ns):
            x.set('content', 'MASKED')
        for i, x in enumerate(root.xpath('//ncx:navPoint', namespaces=ns)):
            x.set('id', f'navpoint{i}')
        for x in root.xpath('//ncx:pageList', namespaces=ns):
            x.set('id', 'pagelist')
        for i, x in enumerate(root.xpath('//ncx:pageTarget', namespaces=ns)):
            x.set('id', f'pagetarget{i}')
    return etree.tostring(root, method='c14n')


def summarize_epub(path):
    ans = {}
    with zipfile.ZipFile(path) as zf:
        for zi in zf.infolist():
            raw = zf.read(zi)
            if zi.filename.endswith(('.opf', '.ncx', '.html', '.xhtml')):
                raw = normalize_xml(raw, zi.filename)
            elif zi.filename.endswith('.css'):
                raw = raw.replace(b'\r\n', b'\n')
            ans[zi.filename] = sha(raw)
    return ans


def summarize(path):
    return summarize_epub(path) if path.endswith('.epub') else summarize_mobi(path)


def diff_summaries(expected, actual, path=''):
    """List the components that differ"""
    if isinstance(expected, dict) and isinstance(actual, dict):
        ans = []
        for k in sorted(set(expected) | set(actual)):
            if k not in expected:
                ans.append(f'{path}/{k}: unexpected, new value {actual[k]!r}')
            elif k not in actual:
                ans.append(f'{path}/{k}: missing, expected {expected[k]!r}')
            else:
                ans.extend(diff_summaries(expected[k], actual[k], f'{path}/{k}'))
        return ans
    if isinstance(expected, list) and isinstance(actual, list) and len(expected) == len(actual):
        ans = []
        for i, (e, a) in enumerate(zip(expected, actual)):
            ans.extend(diff_summaries(e, a, f'{path}[{i}]'))
        return ans
    if expected != actual:
        return [f'{path}: expected {expected!r}, got {actual!r}']
    return []


