"""
Property tests for the caches of the db.Cache: a Cache that has lived through a
sequence of writes must give exactly the same answers as a Cache freshly opened
on the same library from disk, which has nothing cached and recomputes
everything.

The caches covered are the search LRU cache and parse cache (db/search.py), the
composite column render cache (db/fields.py), the formatter template cache, the
cached categories (db/categories.py), vls_for_books_cache, link_maps_cache,
extra_files_cache, format_metadata_cache, dirtied_cache and the maps of the
legacy View (db/view.py). The Virtual libraries go through the search cache.

test_random_operations() drives the live Cache with a seeded random sequence of
operations through its public API, comparing it with a fresh Cache after every
operation, see Harness.observe() for what is compared. When it finds a
difference it prints the operations performed and a shrunk version of the
sequence that still exhibits the same difference, which can be replayed with
Harness.run().

Every stale cache found this way has a minimal deterministic test, marked
expectedFailure, named test_stale_*. The operations that trigger it are not
generated by the random test, the comment in the generator (the gen_* methods
of Harness) or in Harness.populate() says which test documents why. When
a cache is fixed, remove expectedFailure from its test and remove the
exclusion from the generator, so that the random test covers the fix.
"""

