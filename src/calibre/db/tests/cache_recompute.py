    # Observing a library {{{
    def fresh_cache(self):
        from calibre.db.backend import DB
        from calibre.db.cache import Cache

        # Hold the write lock so that the background threads of the live cache
        # do not use the database while the new connection is being set up
        with self.cache.quiet_write_lock:
            fresh = Cache(DB(self.library_path))
            fresh.init()
        self.fresh_count += 1
        return fresh

    @staticmethod
    def observe(cache, view):
        "Return a dict mapping the description of an observation to the value observed"
        ans = {}

        def put(key, func, *args):
            ans[key] = normalize(attempt(func, *args))

        all_ids = sorted(cache.all_book_ids())
        # Search: the same searches are made all the time so that the search
        # cache is populated and has to be kept up to date by the writes
        for q in QUERIES:
            put(f'search[{q}]', lambda q: tuple(sorted(cache.search(q))), q)
        for q, r in RESTRICTED_SEARCHES:
            put(f'search[{q!r}, restriction={r}]', lambda q, r: tuple(sorted(cache.search(q, r))), q, r)
        for name in VIRTUAL_LIBRARIES:
            put(f'books_in_virtual_library[{name}]', lambda name: tuple(sorted(cache.books_in_virtual_library(name))), name)
            put(f'books_in_virtual_library[{name}, restriction]', lambda name: tuple(sorted(cache.books_in_virtual_library(name, 'tags:true'))), name)
        put('virtual_libraries_for_books', lambda: tuple(sorted(cache.virtual_libraries_for_books(all_ids).items())))
        # Composite columns, through the three ways of getting their value
        composites = sorted(f for f, fm in cache.field_metadata.custom_field_metadata().items() if fm['datatype'] == 'composite')
        for bid in all_ids:
            mi, pmi = attempt(cache.get_metadata, bid), attempt(cache.get_proxy_metadata, bid)
            for f in composites:
                put(f'composite[{f}, {bid}]', cache.field_for, f, bid)
                put(f'composite_get_metadata[{f}, {bid}]', lambda f: mi.get(f), f)  # noqa: PLW0108
                put(f'composite_proxy[{f}, {bid}]', lambda f: pmi.get(f), f)  # noqa: PLW0108
        # The caches of the links, the extra files, the metadata of format files and the books that need a metadata backup
        for bid in all_ids:
            put(f'link_maps[{bid}]', cache.get_all_link_maps_for_book, bid)
            put(
                f'extra_files[{bid}]',
                lambda bid: tuple((x.relpath, x.stat_result.st_size, int(x.stat_result.st_mtime)) for x in cache.list_extra_files(bid, use_cache=True)),
                bid,
            )
            for fmt in FORMATS:
                put(
                    f'format_metadata[{bid}, {fmt}]',
                    lambda bid, fmt: {k: v for k, v in cache.format_metadata(bid, fmt).items() if k in ('size', 'mtime')},
                    bid,
                    fmt,
                )
        put('dirtied', lambda: tuple(sorted(cache.dirtied_cache)))
        # Categories, which are also cached when they are not restricted to a set of books
        series_fields = {f for f, fm in cache.field_metadata.items() if fm['datatype'] == 'series'}
        subsets = {'all': None, 'odd': frozenset(x for x in all_ids if x % 2), 'vl': attempt(cache.books_in_virtual_library, 'VL Series')}
        for sort in ('name', 'popularity'):
            for sname, book_ids in subsets.items():
                cats = attempt(lambda: cache.get_categories(sort=sort, book_ids=book_ids))
                for cat, tags in cats.items() if isinstance(cats, dict) else (('categories', cats),):
                    ans[f'categories[{cat}, sort={sort}, books={sname}]'] = canonical_category(tags, sort, series_fields)
        # Sorting
        for spec in SORT_SPECS:
            put(f'multisort[{spec}]', lambda spec: tuple(cache.multisort(list(spec))), spec)
            put(f'multisort[{spec}, vl]', lambda spec: tuple(cache.multisort(list(spec), ids_to_sort=cache.books_in_virtual_library('VL Tagged'))), spec)
        # The legacy View, which is refreshed without clearing the caches
        view.refresh(clear_caches=False, do_search=False)
        ans['view._map'] = view._map

        def view_search(field, ascending, restriction, query):
            view.set_search_restriction(restriction)
            view.multisort([(field, ascending), ('id', True)])
            view.search(query)
            return tuple(view._map_filtered), view.get_search_restriction_book_count()

        for case in VIEW_CASES:
            put(f'view[{case}]', view_search, *case)
        view.set_search_restriction('')
        view.refresh(clear_caches=False, do_search=False)
        # The page count is None in memory for a book awaiting a page count and the
        # size of a book without formats is 0 in memory but None for a fresh cache
        # and the order of the formats and identifiers is that of their addition in memory
        fmap = cache.backend.FIELD_MAP
        skip, size, formats, identifiers = fmap['pages'], fmap['size'], fmap['formats'], fmap['identifiers']

        def view_value(bid, loc):
            ans = view.get_property(bid, True, loc)
            if loc == size:
                return ans or 0
            if loc in (formats, identifiers):
                return sorted(ans.split(',')) if ans else ans
            return ans

        for bid in all_ids:
            put(f'view_row[{bid}]', lambda bid: tuple(view_value(bid, loc) for loc in range(view.column_count) if loc != skip), bid)
        return ans

    def compare(self):
        "Return None if the live cache agrees with a fresh cache, otherwise a description of the first difference"
        from calibre.db.view import View

        live = self.observe(self.cache, self.view)
        fresh = self.fresh_cache()
        try:
            fresh_view = View(fresh)
            fresh_view.set_marked_ids(self.view.marked_ids)
            expected = self.observe(fresh, fresh_view)
        finally:
            fresh.close()
        if live.keys() != expected.keys():
            return 'observations', f'Different observations: {sorted(live.keys() ^ expected.keys())[:5]}'
        for k, v in live.items():
            if v != expected[k]:
                return k, f'{k}\n  live cache: {v!r}\n  fresh cache: {expected[k]!r}'

