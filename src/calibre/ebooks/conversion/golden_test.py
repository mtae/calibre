def write_inputs(tdir):
    ans = {}
    for name, (builder, ext, args) in BOOKS.items():
        path = os.path.join(tdir, f'{name}.{ext}')
        if ext == 'txt':
            with open(path, 'w', encoding='utf-8') as f:
                f.write(builder())
        else:
            chapters, css, imgs = builder()
            make_epub(path, chapters, css, imgs, title=f'Golden {name}')
        ans[name] = path
    with open(os.path.join(tdir, 'cover.jpg'), 'wb') as f:
        f.write(jpeg_bytes(90, 120))
    return ans


