def book_images():
    """Eight PNG and JPEG images in two chapters, one of them used twice"""
    body1, body2, imgs = ['<h1>Pictures</h1>'], ['<h1>More</h1>'], []
    for i in range(8):
        if i % 2:
            imgs.append((f'i{i}.jpg', 'image/jpeg', jpeg_bytes(40 + 4 * i, 30 + 3 * i)))
        else:
            imgs.append((f'i{i}.png', 'image/png', png_bytes(30 + 3 * i, 20 + 2 * i)))
        (body1 if i < 5 else body2).append(f'<p>Image {i}: <img src="{imgs[-1][0]}" alt="image {i}"/></p>')
    body2.append('<p>Repeat: <img src="i0.png" alt="again"/></p>')
    chapters = [('c1.html', 'Pictures', '\n'.join(body1)), ('c2.html', 'More pictures', '\n'.join(body2))]
    return chapters, 'img { max-width: 100% }', imgs


def book_txt():
    """Plain text with hard wrapped lines, hyphenated words, chapter headings and scene breaks, converted with heuristics enabled"""
    paras = []
    for i in range(1, 4):
        paras.append(f'CHAPTER {i}\n')
        for j in range(4):
            lines = (LOREM * 2 + 'An exam-\nple of a hyphen-\nated word and "quoted" text...').split('. ')
            paras.append('\n'.join(x.strip() for x in lines if x.strip()) + '\n')
        paras.append('* * *\n')
        paras.append('    ' + LOREM + '\n')
    return '\n'.join(paras)


