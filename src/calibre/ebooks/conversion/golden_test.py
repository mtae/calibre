def convert(src, dest, cover, extra_args=()):
    """Convert in this process, with the random/time based values fixed (see calibre.ebooks.oeb.reproducible)"""
    from unittest import mock

    from calibre.ebooks.conversion.cli import main
    from calibre.ebooks.oeb import reproducible

    with mock.patch.dict(os.environ, {'SOURCE_DATE_EPOCH': SOURCE_DATE_EPOCH}):
        reproducible.reset()
        out = io.StringIO()
        with redirect_stdout(out), redirect_stderr(out):
            ret = main(['ebook-convert', src, dest, '--cover', cover, *extra_args])
    if ret:
        raise AssertionError(f'Conversion of {src} to {dest} failed with: {out.getvalue()}')


