"""
Golden tests for the conversion pipeline.

A few small books are generated by the tests (no binary fixtures) and
converted to EPUB, AZW3 and MOBI in-process. For every output a canonical
summary is computed and compared with the expected one in
golden_expected.json, next to this file:

* MOBI/AZW3: header fields, the SHA-256 and length of the decompressed text
  (all text records joined, including the recindex/kindle:embed numbers), the
  trailing data of the text records (indexing/TBS), the format and size of
  every image record in order and a hash of every other record. Record 0 and
  the PalmDB header are not part of the summary as they contain times, ids
  and the calibre version. The pixel data of images is not compared (lossy
  encoders differ between library versions), but test_deterministic_across_processes
  compares complete files from two processes.
* EPUB: the SHA-256 of every file in the zip. OPF, NCX and
  XHTML files are normalized first: uuids, timestamps, the producer name
  with the calibre version and the random ids of the NCX nav points are
  masked and the XML is canonicalized. Modification times in the zip are
  ignored.

If a conversion changes on purpose, regenerate the expected values with

    CALIBRE_GOLDEN_REGENERATE=1 python setup.py test --test-module ebooks \\
        -n golden_text_toc -n golden_heavy_css -n golden_images -n golden_txt_heuristics

(it only rewrites the entries of the tests that were run), then REVIEW
`git diff src/calibre/ebooks/conversion/golden_expected.json`: every changed
hash must be explained by your change (a changed hash only says that the output
changed, not whether it is still correct). When a test fails it lists the
changed components. To look at the actual outputs set
CALIBRE_GOLDEN_KEEP=/some/dir, the converted books are then copied there.
"""

