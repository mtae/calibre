def convert_in_worker(tdir, seed_dir):
    """Run in a separate process (see test_deterministic_across_processes). Returns the hash of every output file, with zip times ignored."""
    ans = {}
    inputs = write_inputs(tdir)
    cover = os.path.join(tdir, 'cover.jpg')
    for book in ('css', 'images'):
        for fmt in FORMATS:
            dest = os.path.join(seed_dir, f'{book}.{fmt}')
            convert(inputs[book], dest, cover, BOOKS[book][2])
            if fmt == 'epub':
                with zipfile.ZipFile(dest) as zf:
                    ans[f'{book}.{fmt}'] = {zi.filename: sha(zf.read(zi)) for zi in zf.infolist()}
            else:
                with open(dest, 'rb') as f:
                    ans[f'{book}.{fmt}'] = sha(f.read())
    return ans


def find_tests():
    from calibre.ptempfile import TemporaryDirectory

    class GoldenConversion(unittest.TestCase):
        maxDiff = None
        regenerate = bool(os.environ.get('CALIBRE_GOLDEN_REGENERATE'))

        @classmethod
        def setUpClass(cls):
            cls.expected = {}
            if os.path.exists(EXPECTED):
                with open(EXPECTED, encoding='utf-8') as f:
                    cls.expected = json.load(f)
            cls.actual = {}
            cls.tdir_ctx = TemporaryDirectory('_golden')
            cls.tdir = cls.tdir_ctx.__enter__()
            cls.inputs = write_inputs(cls.tdir)
            cls.out = os.path.join(cls.tdir, 'out')
            os.mkdir(cls.out)
            cls.cover = os.path.join(cls.tdir, 'cover.jpg')

        @classmethod
        def tearDownClass(cls):
            keep = os.environ.get('CALIBRE_GOLDEN_KEEP')
            if keep:
                shutil.copytree(cls.tdir, keep, dirs_exist_ok=True)
            cls.tdir_ctx.__exit__(None, None, None)
            if cls.regenerate and cls.actual:
                merged = {}
                if os.path.exists(EXPECTED):  # re-read as tests can run in several processes
                    with open(EXPECTED, encoding='utf-8') as f:
                        merged = json.load(f)
                merged.update(cls.actual)
                with open(EXPECTED, 'w', encoding='utf-8') as f:
                    json.dump(merged, f, indent=1, sort_keys=True)
                    f.write('\n')

        def check_book(self, book):
            for fmt in FORMATS:
                with self.subTest(book=book, fmt=fmt):
                    dest = os.path.join(self.out, f'{book}.{fmt}')
                    convert(self.inputs[book], dest, self.cover, BOOKS[book][2])
                    key = f'{book}.{fmt}'
                    actual = summarize(dest)
                    self.actual[key] = actual
                    if self.regenerate:
                        continue
                    self.assertIn(key, self.expected, f'No expected value for {key}, see the docstring of {__name__} on how to generate it')
                    diffs = diff_summaries(self.expected[key], actual)
                    self.assertFalse(diffs, f'{key} changed:\n' + '\n'.join(diffs[:40]))

        def test_golden_text_toc(self):
            self.check_book('text')

        def test_golden_heavy_css(self):
            self.check_book('css')

        def test_golden_images(self):
            self.check_book('images')

        def test_golden_txt_heuristics(self):
            self.check_book('txt')

        def test_summaries_detect_changes(self):
            # make sure the summaries are sensitive to what they should be
            dest = os.path.join(self.out, 'sens.mobi')
            convert(self.inputs['images'], dest, self.cover)
            a = summarize_mobi(dest)
            other = os.path.join(self.out, 'sens2.mobi')
            convert(self.inputs['text'], other, self.cover)
            self.assertTrue(diff_summaries(a, summarize_mobi(other)))
            self.assertEqual(a['header']['version'], 6)
            self.assertEqual(len([x for x in a['records'] if x[0] == 'image']), 8 + 2)  # 8 images, cover and its thumbnail
            self.assertEqual(diff_summaries(a, summarize_mobi(dest)), [])

    class Reproducible(unittest.TestCase):
        def test_reproducible_helpers(self):
            from unittest import mock

            from calibre.ebooks.oeb import reproducible as r

            def values():
                r.reset()
                return (
                    r.epoch_seconds(),
                    r.random_uint32(),
                    r.random_uint32(),
                    str(r.uuid4()),
                    r.short_uuid4(),
                    r.random_bytes(20),
                    r.random_bytes(70),
                    r.datetime_now().isoformat(),
                )

            with mock.patch.dict(os.environ, {'SOURCE_DATE_EPOCH': '1577923200'}):
                a, b = values(), values()
                self.assertEqual(a, b)
                self.assertEqual(a[0], 1577923200)
                self.assertNotEqual(a[1], a[2])
                self.assertEqual((len(a[5]), len(a[6])), (20, 70))
                self.assertTrue(a[7].startswith('2020-01-02T00:00:00'))
                r.reset()
                self.assertNotEqual(str(r.uuid4()), str(r.uuid4()))
            with mock.patch.dict(os.environ, {'SOURCE_DATE_EPOCH': 'not a number'}):
                self.assertIsNone(r.source_date_epoch())
            env = {k: v for k, v in os.environ.items() if k != 'SOURCE_DATE_EPOCH'}
            with mock.patch.dict(os.environ, env, clear=True):
                self.assertIsNone(r.source_date_epoch())
