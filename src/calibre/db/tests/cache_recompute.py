def shrink(test, ops, key):
    """
    Delta debugging: return a smaller subsequence of ops that still makes the
    live cache differ from a fresh cache in the observation named key
    """

    def fails(candidate):
        h = Harness(test)
        res = h.run(candidate)
        h.cache.close()
        test.objects_to_close.remove(h.cache) if h.cache in test.objects_to_close else None
        return res is not None and res[1] == key

    n = 2
    ops = list(ops)
    while len(ops) >= 2:
        chunk = max(1, len(ops) // n)
        reduced = False
        for start in range(0, len(ops), chunk):
            candidate = ops[:start] + ops[start + chunk :]
            if candidate and fails(candidate):
                ops, n, reduced = candidate, max(n - 1, 2), True
                break
        if not reduced:
            if chunk == 1:
                break
            n = min(len(ops), n * 2)
    return ops


class CacheRecomputeTest(BaseTest):
    def setUp(self):
        from unittest.mock import patch

        super().setUp()
        # The page counts are computed by a background thread, which would make
        # the test non deterministic, the counting would fail for the fake
        # books and starting and stopping the thread for every fresh cache is slow
        p = patch('calibre.db.page_count.MaintainPageCounts.start', lambda self: None)
        p.start()
        self.addCleanup(p.stop)

    def fresh(self, cache):
        "A Cache opened on the library of the specified cache from disk, with nothing cached"
        from calibre.db.backend import DB
        from calibre.db.cache import Cache

        with cache.quiet_write_lock:
            ans = Cache(DB(cache.backend.library_path))
            ans.init()
        self.objects_to_close.append(ans)
        return ans

    def find_difference(self, seed, num_ops):
        """
        Perform num_ops random operations, comparing the live cache with a
        fresh one after each. Return None if all is well, otherwise a tuple
        (index of the operation, key of the observation, description, all the
        operations performed up to and including the one that failed)
        """
        h = Harness(self)
        try:
            rng = random.Random(seed)
            diff = h.compare()
            self.assertIsNone(diff, 'The initial library is inconsistent')
            ops = []
            for i in range(num_ops):
                op = h.generate(rng)
                ops.append(op)
                h.apply(op)
                diff = h.compare()
                if diff is not None:
                    return i, *diff, ops
        finally:
            h.close()

    def run_random(self, seed, num_ops):
        res = self.find_difference(seed, num_ops)
        if res is not None:
            i, key, desc, ops = res
            small = shrink(self, ops, key)
            self.fail(
                f'Seed {seed}: after operation {i} the live cache differs from a fresh cache in {key}\n{desc}\n'
                f'Operations: {ops!r}\nMinimal sequence that still differs in {key}:\n{small!r}'
            )

    def cache_with_composites(self, **templates):
        "A Cache for the test library with composite columns with the specified templates"
        cache = self.init_cache()
        for label, template in templates.items():
            cache.create_custom_column(label, label, 'composite', False, display={'composite_template': template})
        cache.close()
        self.objects_to_close.remove(cache)
        return self.init_cache()

    def assert_same_as_fresh(self, cache, what, *args):
        "Assert that calling the named read API of the live cache gives the same as a fresh cache"
        self.assertEqual(getattr(cache, what)(*args), getattr(self.fresh(cache), what)(*args), f'{what}{args} is stale')

    def test_random_operations(self):
        "Test that a cache which has been written to answers like a freshly opened one"
        # 4 sequences of 50 operations, every operation is followed by a comparison of the
        # many observations of Harness.observe() with a fresh cache. To search for new stale
        # caches try more seeds and longer sequences
        for seed in (11, 12, 13, 14):
            self.run_random(seed, 50)

