def attempt(func, *args, **kw):
    "Call a function, returning the type of the exception it raises instead if it fails, as a search can for a deleted saved search"
    try:
        return func(*args, **kw)
    except Exception as err:
        return 'raised', type(err).__name__


def canonical_category(tags, sort, series_fields):
    """
    A category as a tuple of tuples, with the order of items that have the same
    sort key made canonical, since sorting does not define it. A category with
    items of a series field (a series column or a user category with series in
    it) is compared without the order of its items and without their sort
    values at all, since the sort value of a series is computed in the language
    that most of its books are in, and when several languages are equally
    common which is chosen depends on the iteration order of a set, which is
    not the same for a cache that has been written to and a fresh one. The
    order of the series is covered by multisort.
    """
    if not isinstance(tags, (list, tuple)) or any(isinstance(t, str) for t in tags):
        return tags
    if any(t.category in series_fields for t in tags):
        return tuple(sorted((t.name, t.original_name, t.id, t.count, t.avg_rating, t.category) for t in tags))
    ans = []
    key = (lambda t: (t.count, t.sort)) if sort == 'popularity' else (lambda t: t.sort)
    for _, group in groupby(tags, key):
        ans += sorted((t.name, t.original_name, t.id, t.count, t.avg_rating, t.sort, t.category) for t in group)
    return tuple(ans)


def normalize(x):
    "Timestamps of new books have a microsecond part in memory that is not stored in the database"
    if isinstance(x, datetime):
        return x.astimezone(UTC).replace(microsecond=0)
    if isinstance(x, (list, tuple)):
        return type(x)(normalize(y) for y in x)
    if isinstance(x, dict):
        return {k: normalize(v) for k, v in x.items()}
    return x


